import assert from 'node:assert/strict';
import { readFile, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

// The caller provides the owner of an isolated worker fixture, never a production origin.
export async function testTouchAuthoring(page) {
  assert.equal(new URL(page.url()).hostname, '127.0.0.1');
  page.setDefaultTimeout(12000);
  const tab = name => page.locator('[data-tab="' + name + '"]').click();
  const button = name => page.getByRole('button', {name, exact:true});
  const field = name => page.getByLabel(name, {exact:true});
  const cdp = await page.context().newCDPSession(page);
  const touch = (type, points) => cdp.send('Input.dispatchTouchEvent', {type,touchPoints:points});
  const point = async (element, x=.5, y=.5, id=1) => {
    await element.scrollIntoViewIfNeeded();
    const r = await element.boundingBox();
    return {x:r.x+r.width*x,y:r.y+r.height*y,id};
  };
  await tab('scene');
  await button('빈 맵 만들기').click();
  await field('맵 이름').fill('테스트 지형');
  const mapId = await field('작업 맵').inputValue();
  const stage = page.locator('.stage.edit');
  const start = await point(stage,.12,.82), end = await point(stage,.9,.82);
  await touch('touchStart',[start]); await touch('touchMove',[end]); await touch('touchEnd',[]);
  assert.equal(await stage.locator('.platform').count(),4);
  const testPoint = await point(stage,.55,.55);
  await touch('touchStart',[testPoint]); await touch('touchEnd',[]);
  assert.equal(await stage.locator('.platform').count(),5);
  await button('지형 지우기').click();
  await touch('touchStart',[await point(stage,.56,.55)]); await touch('touchEnd',[]);
  assert.equal(await stage.locator('.platform').count(),4);
  await page.getByText('맵 연결 · 배경 · 관리',{exact:true}).click();
  await field('게임 시작 맵').selectOption(mapId);
  await tab('source');
  await field('실행 환경').selectOption('Unity');
  await field('기기에서 소스 파일 가져오기').setInputFiles({name:'TabletNote.txt',mimeType:'text/plain',buffer:Buffer.from('tablet file')});
  await page.waitForFunction(() => document.querySelector('.code-editor')?.value === 'tablet file');
  assert.equal(await field('소스 파일').inputValue(),'Assets/TabletNote.txt');
  await tab('characters');
  await button('＋ 새 캐릭터').click();
  await field('이름').fill('단비');
  await tab('stories');
  await button('＋ 새 스토리').click();
  const story = await field('작업 스토리').inputValue();
  await field('대사 내용').fill('다리가 여기 있어.');
  await field('화자 표시 이름').fill('길잡이');
  await field('다음 버튼 문구').fill('강 건너기');
  await field('초상 위치').selectOption('right');
  // Exercise both the OS picker event and the Image decoder fallback used by embedded browsers.
  await page.evaluate(() => { window.createImageBitmap = undefined; });
  const file = await readFile(new URL('../art/player.png',import.meta.url));
  const choose = page.waitForEvent('filechooser');
  await field('이 줄의 배경').click();
  await (await choose).setFiles({name:'stage.png',mimeType:'image/png',buffer:file});
  await page.getByText('이미지를 연결했어요. 저장하면 팀 버전에 반영돼요.',{exact:true}).waitFor();
  const portrait = page.locator('.asset-field').filter({has:field('이 줄의 초상')});
  await portrait.getByText('이미지 붙여넣기 · 파일 놓기').click();
  await portrait.locator('textarea').evaluate((el, data) => {
    const bytes = Uint8Array.from(atob(data),c=>c.charCodeAt(0)), dt = new DataTransfer();
    dt.items.add(new File([bytes],'face.png',{type:'image/png'}));
    el.dispatchEvent(new ClipboardEvent('paste',{clipboardData:dt,bubbles:true,cancelable:true}));
  }, file.toString('base64'));
  await portrait.getByRole('button',{name:'이미지 연결 해제'}).waitFor();
  await button('이 줄 복제').click();
  await field('대사 내용').fill('도착했어.');
  await field('다음 버튼 문구').fill('전투로');
  await button('이 줄부터 미리보기').click();
  await page.locator('#reader').getByText('도착했어.',{exact:true}).waitFor();
  await page.locator('#reader .face-right img').waitFor();
  await button('전투로').click();
  await tab('scene');
  if (!(await field('입장 시 대화').isVisible())) await page.getByText('맵 연결 · 배경 · 관리',{exact:true}).click();
  await field('입장 시 대화').selectOption(story);
  await tab('interface');
  await button('시작 화면').click();
  await field('표시 문구').fill('새벽의 다리');
  await button('이 맵에 새 메뉴 만들기').click();
  await field('화면 이름').fill('여행 메뉴');
  await field('표시 문구').fill('여행 계속');
  await page.getByText('버튼 모양 직접 그리기',{exact:true}).click();
  const canvas = page.getByLabel('버튼 외곽선 편집판');
  for (const [x,y] of [[.05,.05],[.95,.05],[.9,.8],[.1,.95]]) {
    await touch('touchStart',[await point(canvas,x,y)]); await touch('touchEnd',[]);
  }
  await button('그린 모양 적용').click();
  assert.equal(await field('버튼 외곽선').inputValue(),'custom');
  await button('전투 HUD').click();
  await button('조이스틱 추가').click();
  await field('너비 (%)').fill('18');
  await field('높이 (%)').fill('30');
  const saved = page.waitForResponse(r=>r.url().endsWith('/api/save'));
  await page.locator('#save').click();
  const reply = await saved;
  assert.equal(reply.status(),200);
  const {project} = await reply.json();
  const map = project.scenes.find(m=>m.id === mapId);
  assert.equal(map.floorMode,'drawn'); assert.equal(map.objects.filter(o=>o.type==='platform').length,4);
  const lines=project.stories.find(s=>s.id===story).nodes;
  assert(lines.every(n=>n.side==='right' && n.backdrop.startsWith('asset:') && n.portrait.startsWith('asset:')));
  assert.equal(project.layouts.find(l=>l.id===map.menuId).elements[0].points.length,4);
  await tab('source');
  await field('실행 환경').selectOption('Web/');
  const download = page.waitForEvent('download');
  await button('초안 → 오프라인 게임 HTML').click();
  const htmlFile = await download;
  const directory = await mkdtemp(join(tmpdir(),'dreamwalker-offline-'));
  const savedFile = join(directory,'game.html');
  await htmlFile.saveAs(savedFile);
  const offline = await page.context().browser().newContext({offline:true});
  try {
    const offlinePage = await offline.newPage();
    await offlinePage.goto(pathToFileURL(savedFile).href);
    const layer = offlinePage.locator('#overlay');
    await layer.getByText('새벽의 다리').waitFor();
    await layer.getByRole('button',{name:'게임 시작'}).click();
    await layer.getByRole('button',{name:'이 캐릭터로 시작'}).click();
    await layer.getByRole('button',{name:'강 건너기'}).click();
    await layer.getByRole('button',{name:'전투로'}).click();
    await layer.locator('.stick-ring').waitFor();
    assert.equal(await offlinePage.locator('#runtime-error').count(),0);
  } finally {
    await offline.close();
    await rm(directory,{recursive:true,force:true});
  }
  await page.goto(new URL('/play',page.url()).href);
  const game = page.locator('#game'), overlay = game.locator('#overlay');
  const act = name => overlay.getByRole('button',{name,exact:true});
  await overlay.getByText('새벽의 다리',{exact:true}).waitFor();
  await act('게임 시작').click();
  await act('다음').click();
  await overlay.locator('.widget-character').getByText('단비',{exact:true}).waitFor();
  await act('이 캐릭터로 시작').click();
  await overlay.locator('.widget-loading').waitFor();
  await overlay.getByText('길잡이',{exact:true}).waitFor();
  assert((await game.locator('#arena').getAttribute('style')).includes('/api/assets/'));
  await act('강 건너기').click();
  await overlay.getByText('도착했어.',{exact:true}).waitFor();
  await act('전투로').click();
  const stick = overlay.locator('.stick-ring'), hero = game.locator('#actors .spawn');
  await hero.waitFor();
  const initial = await hero.evaluate(n=>parseFloat(n.style.left));
  const hold = await point(stick,.95,.5), jump = await point(act('점프'),.5,.5,2);
  await touch('touchStart',[hold]);
  await page.waitForFunction(x=>parseFloat(document.querySelector('#actors .spawn').style.left)>x+1,initial);
  await touch('touchStart',[hold,jump]);
  await page.waitForFunction(()=>parseFloat(document.querySelector('#actors .spawn').style.top)<81);
  await touch('touchCancel',[]);
  const stopped = await hero.evaluate(n=>parseFloat(n.style.left));
  await page.waitForFunction(()=>parseFloat(document.querySelector('#actors .spawn').style.top)>=82);
  assert(Math.abs((await hero.evaluate(n=>parseFloat(n.style.left))) - stopped) < .7);
  await page.evaluate(() => {
    const activate = FieldRun.prototype.activate;
    FieldRun.prototype.activate = function(w) {
      activate.call(this,w);
      if (w.action === 'attack') window.attackWhileMoving = this.stickAxis > 0 && !!this.stroke;
    };
  });
  const attack = await point(act('베기'),.5,.5,2);
  await touch('touchStart',[hold]);
  await touch('touchStart',[hold,attack]);
  await page.waitForFunction(()=>window.attackWhileMoving);
  await touch('touchEnd',[]);
  await act('메뉴').click();
  assert((await act('여행 계속').evaluate(n=>n.style.clipPath)).startsWith('polygon('));
  await act('여행 계속').click();
  await stick.waitFor();
  await cdp.detach();
  console.log('PASS touch-drawn terrain and eraser, native picker & image decoder fallback, clipboard artwork, per-line story direction, title → roster → loading → story → battle, custom menu polygon, simultaneous joystick/jump and attack, release, saved replay and offline HTML');
}
