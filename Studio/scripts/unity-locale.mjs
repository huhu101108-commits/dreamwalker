// Localization for Unity, generated from src/model.js so the two runtimes cannot drift:
//   Assets/Dreamwalker/Scripts/Demo/StudioSystemText.cs   the game's built-in wording (SYSTEM_TEXT)
//   scripts/native-check/locale.json                      keys, applied languages and language picks for the .NET check
//   node scripts/unity-locale.mjs           writes both files
//   node scripts/unity-locale.mjs --check   fails when either file no longer matches the studio
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import vm from 'node:vm';

// New IDs come from a counter so the written files are the same on every run.
let made = 0;
const counted = { randomUUID: () => String(++made).padStart(8, '0') + '-0000-4000-8000-000000000000', subtle: crypto.subtle, getRandomValues: (a) => crypto.getRandomValues(a) };
const ctx = vm.createContext({ crypto: counted, structuredClone, TextEncoder });
vm.runInContext(await readFile(new URL('../src/model.js', import.meta.url), 'utf8'), ctx);
// Constants and arrow functions are not globals of the context; read them out once.
const m = Object.assign(Object.create(ctx), vm.runInContext('({ SYSTEM_TEXT, newEpisode, castDefaults })', ctx));

const csharp = [
  '// Generated by Studio/scripts/unity-locale.mjs from SYSTEM_TEXT in Studio/src/model.js. Do not edit by hand.',
  'using System.Collections.Generic;',
  '',
  'namespace Dreamwalker.Demo',
  '{',
  '// The game\'s own wording in the studio\'s default language. Creators reword and translate it in 번역 · 언어.',
  'public static class StudioSystemText',
  '{',
  '    private static readonly Dictionary<string, string> defaults = new Dictionary<string, string>',
  '    {',
  ...Object.entries(m.SYSTEM_TEXT).map(([k, v]) => '        { ' + JSON.stringify(k) + ', ' + JSON.stringify(v) + ' },'),
  '    };',
  '    public static string Default(string name) => name != null && defaults.TryGetValue(name, out string text) ? text : "";',
  '    public static IEnumerable<string> Names => defaults.Keys;',
  '}',
  '}',
  '',
].join('\n');

// A project with every kind of translatable text, two languages, a reworded and a translated built-in text.
const p = m.seed();
const lead = p.characters[0];
p.title = '설원 횡단';
Object.assign(lead, { region: '북쪽 설원', profile: [{ id: 'unit', label: '소속', value: '설산 경비대' }, { id: 'empty', label: '생일', value: '' }] });
lead.energy = { max: 100, start: 0, hit: 5, hurt: 3, kill: 10 };
lead.skills[0].cast = { ...m.castDefaults(), caption: '서리 일섬', line: '얼어붙어라!' };
lead.roadmap = { entry: 'meet', episodes: [
  { ...m.newEpisode('meet', '첫 만남'), summary: '광산역에서 만난다.', links: [{ label: '따라간다', to: 'chase' }, { label: '돌아간다', to: 'chase' }] },
  m.newEpisode('chase', '추적'),
] };
const map = p.scenes[0];
const foe = map.objects.find((o) => o.type === 'enemy');
foe.enemy.label = foe.label = '서리 늑대';
map.objects.push({ ...m.makeObject('prop', 'sign', 30, 0), label: '낡은 표지판' });
const story = m.newStory('prologue', '프롤로그');
story.nodes = [
  { ...m.newNode('n1'), speaker: lead.id, text: '여기는 {언어}로 말하는 역이야.', nextLabel: '계속 듣기' },
  { ...m.newNode('n2'), speaker: '', speakerName: '안내 방송', text: '어디로 갈까요?', choices: [{ label: '북쪽', to: '' }, { label: '남쪽', to: '' }] },
];
story.nodes[0].shot = m.newShot(story.nodes[0]);
story.nodes[0].shot.layers.push({ ...m.newShotLayer('caption'), id: 'place', caption: '설산 광산역 · 새벽' });
p.stories.push(story);
const screen = p.layouts.find((l) => l.kind === 'menu');
const named = m.widget('callsign', 'input', 10, 10, 40, 10, { text: '호출 부호', control: { ...m.newInputSpec('text'), hint: '이름을 입력', key: 'callsign', validation: { minLength: 1, format: 'word', message: '한 단어로 적어 주세요.' } } });
const level = m.widget('level', 'input', 10, 24, 40, 10, { text: '난이도', control: { ...m.newInputSpec('choice'), options: ['쉬움', '보통'], initial: '쉬움', key: 'level' } });
const swap = m.widget('swap', 'button', 10, 38, 40, 10, { action: 'language', target: '', text: '언어: {언어}' });
screen.elements.push(named, level, swap);
p.items = [{ id: 'sword', name: '서리검', slot: 'weapon', power: 3 }];
p.quests = [{ id: 'first', name: '첫 의뢰', kind: 'clear', target: p.startMap, reward: 'sword', count: 1 }];
p.shop = { currencies: [{ id: 'gem', name: '결정', start: 100, max: 9999, icon: '' }],
  products: [{ id: 'pack', name: '결정 꾸러미', cost: { kind: 'money', amount: 1200, sku: 'gem.pack' }, gives: [{ kind: 'currency', id: 'gem', count: 300 }], limit: 0 }],
  banners: [{ id: 'snow', name: '설원 뽑기', image: '', cost: { currency: 'gem', amount: 160 }, multi: 10, pity: 0,
    tiers: [{ id: 'top', name: '전설', rate: 2000, top: true, entries: [{ kind: 'item', id: 'sword', count: 1, weight: 1 }] },
      { id: 'low', name: '일반', rate: 98000, top: false, entries: [{ kind: 'currency', id: 'gem', count: 5, weight: 1 }] }] }] };
p.locales = { ...m.emptyLocales(), languages: [{ code: 'en', name: 'English' }, { code: 'ja', name: '日本語' }], system: { 'result.clear': '탐험 성공' } };
const slots = new Map(m.textSlots(p, { system: true }).map((s) => [s.key, s]));
const say = (key, code, text, from = slots.get(key).owner[slots.get(key).field]) => m.setTranslation(p, key, code, text, from);
for (const [key, text] of [
  ['title', 'Snowfield Crossing'], ['character/' + lead.id + '/name', 'Baekseol'], ['character/' + lead.id + '/profile/unit', 'Snow Guard'],
  ['character/' + lead.id + '/skill/0/caption', 'Frost Flash'], ['character/' + lead.id + '/skill/0/line', 'Freeze!'],
  ['character/' + lead.id + '/episode/meet/title', 'First Meeting'], ['character/' + lead.id + '/episode/meet/link/1', 'Go back'],
  ['map/' + map.id + '/name', 'Mine Station'], ['map/' + map.id + '/object/' + foe.id + '/label', 'Frost Wolf'],
  ['story/prologue/line/n1/text', 'This station speaks {언어}.'], ['story/prologue/line/n1/next', 'Keep listening'],
  ['story/prologue/line/n1/layer/place', 'Mine station · dawn'], ['story/prologue/line/n2/speaker', 'Announcement'],
  ['story/prologue/line/n2/choice/0', 'North'], ['screen/' + screen.id + '/callsign/hint', 'Enter a name'],
  ['screen/' + screen.id + '/callsign/message', 'Use one word.'], ['screen/' + screen.id + '/level/option/1', 'Normal'],
  ['screen/' + screen.id + '/swap/text', 'Language: {언어}'], ['item/sword/name', 'Frost Sword'], ['quest/first/name', 'First Job'],
  ['system/button.jump', 'Jump'], ['system/result.clear', 'Explored'], ['system/dialogue.next', 'Next →'],
  ['shop/currency/gem/name', 'Crystal'], ['shop/banner/snow/name', 'Snowfield Pull'], ['shop/banner/snow/tier/top/name', 'Legend'],
]) say(key, 'en', text);
say('character/' + lead.id + '/name', 'ja', '白雪');
say('story/prologue/line/n2/text', 'ja', '古い原文の訳', '예전 원문');
p.locales.strings['map/gone/name'] = { en: { text: 'Removed map', src: '00000000' } };
assert.equal(m.problem(p), '', 'the sample project is valid');

const packed = JSON.parse(JSON.stringify(m.packNativeWorld(p)));
assert(!packed.locales && packed.locale, 'Unity gets the packed locale only');
assert(!packed.locale.keys.includes('map/gone/name'), 'translations of removed text stay out of the game');
// The fields localization touches; the .NET check reads them with the Unity classes.
const pick = (o, keys) => Object.fromEntries(keys.filter((k) => o[k] !== undefined).map((k) => [k, o[k]]));
const project = {
  title: packed.title, startMap: packed.startMap, saveId: packed.saveId ?? '', locale: packed.locale,
  characters: packed.characters.map((c) => ({ ...pick(c, ['id', 'name', 'region', 'summary', 'profile']),
    skills: c.skills.map((s) => pick(s, ['name', 'cast'])), roadmap: c.roadmap })),
  scenes: packed.scenes.map((s) => ({ id: s.id, name: s.name, objects: s.objects.map((o) => pick(o, ['id', 'type', 'label'])) })),
  stories: packed.stories.map((s) => ({ id: s.id, name: s.name, nodes: s.nodes.map((n) => ({
    ...pick(n, ['id', 'speaker', 'text', 'speakerName', 'nextLabel', 'choices']),
    ...(n.shot ? { shot: { layers: n.shot.layers.map((l) => pick(l, ['id', 'kind', 'caption'])) } } : {}) })) })),
  layouts: packed.layouts.map((l) => ({ id: l.id, name: l.name, kind: l.kind, elements: l.elements.map((w) => pick(w, ['id', 'type', 'text', 'action', 'target', 'control'])) })),
  items: packed.items, quests: packed.quests, shop: packed.shop,
};
const read = (world) => m.textSlots(world, { play: true }).map((s) => [s.key, s.owner[s.field]]);
const keys = read(structuredClone(project));
const world = structuredClone(m.playableWorld(p));
const applied = {};
for (const code of ['en', 'ja', 'ko']) {
  m.localizeWorld(world, code);
  applied[code] = { values: read(world), system: Object.keys(m.SYSTEM_TEXT).map((n) => [n, m.systemText(world, n)]) };
}
const codes = ['ko', 'en', 'ja', 'zh-Hans', 'zh-Hant', 'pt-BR'];
const picks = [['en-US'], ['zh-TW'], ['zh-CN'], ['zh'], ['pt-PT'], ['fr', 'ja-JP'], ['', ''], ['de'], ['ZH-hant-HK'], ['en_GB'], ['zh-Hant'], ['zh-SG'], ['zh-MO']]
  .map((wanted) => [codes, wanted, m.pickLanguage(codes, wanted)]);
const fixture = JSON.stringify({ project, keys, applied, picks }, null, 1) + '\n';

const files = [[new URL('../../Assets/Dreamwalker/Scripts/Demo/StudioSystemText.cs', import.meta.url), csharp],
  [new URL('./native-check/locale.json', import.meta.url), fixture]];
if (process.argv.includes('--check')) {
  for (const [url, text] of files)
    if ((await readFile(url, 'utf8').catch(() => '')) !== text) {
      console.error('FAIL ' + url.pathname + ' differs from the studio. Run: node scripts/unity-locale.mjs');
      process.exit(1);
    }
  console.log('PASS Unity localization files match the studio: ' + Object.keys(m.SYSTEM_TEXT).length + ' built-in texts, ' + keys.length + ' keys, ' + picks.length + ' language picks');
} else {
  for (const [url, text] of files) await writeFile(url, text);
  console.log('Wrote StudioSystemText.cs and native-check/locale.json');
}
