import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const ctx = vm.createContext({ crypto, structuredClone });
vm.runInContext(['model', 'simulation'].map(n => fs.readFileSync('src/' + n + '.js', 'utf8')).join('\n'), ctx);
const { seed, problem, migrateProject, newMap, makeObject, FieldRun, MapGrid, inspectScreens, newScreen, newRule } =
  vm.runInContext('({seed,problem,migrateProject,newMap,makeObject,FieldRun,MapGrid,inspectScreens,newScreen,newRule})',ctx);
const d = seed(), m = d.scenes[0];
m.width = 3200; m.height = 1600;
const hall = newMap('hall','검수 맵'); d.scenes.push(hall);
const legacy = structuredClone(d);
delete legacy.scenes[0].height; delete legacy.scenes[0].camera; delete legacy.tuning.startupTicks;
assert.equal(problem(migrateProject(legacy)), '');
assert.equal(legacy.scenes[0].height, undefined);
m.objects.find(o => o.type === 'spawn').x = 150;
const r = new FieldRun(d), h = r.hero, enemy = r.foes[0];
for (const foe of r.foes) { foe.enemy.speed = 0; foe.enemy.damage = 0; }
enemy.x = h.x + 3;
r.press('attack'); assert.equal(enemy.hp,100);
for (let i=0; i<6; i++) r.tick(1/60);
assert.equal(enemy.hp,100);
for (let i=0; i<7; i++) r.tick(1/60);
assert.equal(enemy.hp,82);
r.press('attack');
for (let i=0; i<26; i++) r.tick(1/60);
assert.equal(enemy.hp,64);
const camera = r.camera;
h.x += 30; h.y = 90; r.tick(1/60);
assert(r.camera > camera && r.camera < h.x-46);
assert(r.viewport.y > 0 && r.viewport.y < h.y-36);
r.stroke = null; h.hp=24; r.press('flagOn','진행'); r.foes[1].hp=0;
r.press('gotoMap','hall'); assert.equal(r.hero.hp,24);
r.press('gotoMap',m.id); assert.equal(r.foes[1].hp,0);
r.foes[0].hp=53;
const check = JSON.parse(JSON.stringify(r.checkpoint()));
const other = new FieldRun(d);
assert(other.restore(check));
assert.equal(other.hero.hp,24); assert.equal(other.foes[0].hp,53); assert(other.flags.has('진행'));
assert.equal(other.restore({ ...check, map:'missing' }),false);
r.press('newRun'); assert.equal(r.hero.hp,100); assert(!r.flags.has('진행')); assert.equal(r.foes[1].hp,100);
const bad = newScreen('trap','복귀 검사','custom'); bad.rules = [newRule('start')];
bad.elements[0].showFlag='없는상태'; bad.elements[0].showValue=true;
d.layouts.push(bad); assert(inspectScreens(d).errors.some(v=>v.includes('복귀 검사')));
bad.elements[0].showFlag=''; assert.equal(inspectScreens(d).errors.length,0);
const platform = makeObject('platform','lift',150,5); platform.motion={ dx:12,dy:7,period:2 };
m.objects.push(platform); m.objects[0].y=5;
const liftRun=new FieldRun(d); liftRun.press('resume');
for(let i=0;i<60;i++) liftRun.tick(1/60);
assert(Math.abs(liftRun.hero.y-12)<0.02);
const props = Array.from({length:160},(_,i)=> ({id:'p'+i,x:4+20*i,y:(i%3)*12,width:4,height:6}));
const grid = new MapGrid(props), visible = new Set();
let visits=0;
for (let i=0;i<600;i++) {
  const x=i*5;
  grid.query(x-6,-20,x+106,88,visible);
  visits+=visible.size;
  for(const p of props) if(p.x+p.width/2>=x && p.x-p.width/2<=x+100) assert(visible.has(p));
}
assert(visits < props.length*600/4);
console.log('PASS production: 6/7/13 attack and input buffer, checkpoint and travel HP, vertical camera, moving lift, touch recovery, spatial index');
console.log('600 camera positions × 160 stationary props: full scan '+(props.length*600)+', spatial candidates '+visits);
