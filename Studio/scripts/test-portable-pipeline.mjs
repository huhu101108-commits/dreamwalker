import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
const png=await fs.readFile('art/player.png');
const sound=Buffer.from('RIFF0000WAVEdata-preset-fixture');
const hash=async bytes=>Buffer.from(await crypto.subtle.digest('SHA-256',bytes)).toString('hex');
const img='asset:'+await hash(png),audio='asset:'+await hash(sound);
const server=new Map([[img,new Blob([png],{type:'image/png'})],[audio,new Blob([sound],{type:'audio/wav'})]]);
const fetcher=async(url,opts)=>{
  if(url.startsWith('data:'))return fetch(url);
  const blob=server.get('asset:'+url.split('/').pop());
  return new Response(blob&&opts?.method!=='HEAD'?blob:null,{status:blob?200:404,headers:blob?{'content-type':blob.type}:{}});
};
const ctx=vm.createContext({crypto,structuredClone,Uint8Array,Blob,fetch:fetcher,toDataUrl:async b=>'data:'+b.type+';base64,'+Buffer.from(await b.arrayBuffer()).toString('base64')});
for(const name of ['model','rule-machine','preset-editor','export'])vm.runInContext(await fs.readFile('src/'+name+'.js','utf8'),ctx);
const m=vm.runInContext('({seed,newCharacter,newClip,emptyWork,widget,capturePreset,validStudioPreset,problem,presetFileRefs,bindToPreset,updatePresetInstances,imageRefs,soundRefs,packNativeWorld,makePortableBundle,inspectPortableBundle,presetExternalTargets,replacePresetMedia,inspectOutput,nativePackIndex,portablePresetCopy,controlPresetElements})',ctx);
const a=m.seed(),b=m.seed();
a.work=m.emptyWork();a.work.presets=[];
const hero=a.characters[0];hero.clips={attack:{...m.newClip(),sound:audio,frames:[{image:img,ticks:4}]}};hero.portrait=img;
const preset={id:'saved',kind:'character',name:'이동 검사',data:m.capturePreset(a,'character',hero)};
a.work.presets.push(preset);
assert.equal(m.problem(a),'');assert(!('name' in preset.data));assert.equal(m.presetFileRefs(preset).length,2);
const bundle=await m.makePortableBundle(preset);assert.equal(Object.keys(bundle.assets).length,2);assert(!JSON.stringify(bundle).includes('sourceFiles'));
const restore=await m.inspectPortableBundle(bundle,b,'character');assert.equal(restore.blobs.size,2);assert.equal(restore.missing.length,0);
const bad=structuredClone(bundle);bad.assets[img.slice(6)]='data:image/png;base64,aGk=';await assert.rejects(m.inspectPortableBundle(bad,b,'character'),/원본과 다른/);
const absent=structuredClone(bundle);delete absent.assets[img.slice(6)];server.delete(img);
const repair=await m.inspectPortableBundle(absent,b,'character');assert.equal(repair.missing[0].ref,img);
const replacement='asset:'+'c'.repeat(64);m.replacePresetMedia(repair.preset,img,replacement);assert.equal(repair.preset.data.clips.attack.frames[0].image,replacement);
assert.equal(preset.data.clips.attack.frames[0].image,img);
const copied=m.portablePresetCopy(preset,a.work.presets);assert.notEqual(copied.id,preset.id);assert.notEqual(copied.name,preset.name);
const actor=m.newCharacter('second','검수 캐릭터');
Object.assign(actor,structuredClone(preset.data));a.characters.push(actor);
m.bindToPreset(a,preset,'',actor.id);actor.health=333;
const edited=structuredClone(preset);edited.data.health=211;edited.data.speedScale=2.5;
m.updatePresetInstances(a,preset,edited);assert.deepEqual([actor.health,actor.speedScale,actor.name],[333,2.5,'검수 캐릭터']);assert.equal(hero.speedScale,1);
const native=m.packNativeWorld(a);assert(!native.work);assert.equal(native.characters.find(c=>c.id===actor.id).speedScale,2.5);
hero.clips={};hero.portrait='';a.characters=a.characters.filter(c=>c.id!==actor.id);
assert(m.soundRefs(a).includes(audio.slice(6)));assert(m.imageRefs(a).includes(img.slice(6)));
assert(!m.imageRefs(m.packNativeWorld(a)).includes(img.slice(6)));assert(!m.soundRefs(m.packNativeWorld(a)).includes(audio.slice(6)));
const screen=b.layouts.find(l=>l.kind==='hud'), pair=m.capturePreset(b,'controls',screen);assert(pair.elements.length);
const mixed=structuredClone(screen);mixed.elements=[m.widget('keep','text',0,0,15,10,{text:'고정'})];
const controls={id:'layout-controls',name:'조작',kind:'controls',data:pair};const restored=m.controlPresetElements(b,controls,mixed);assert.equal(restored[0].id,'keep');assert.equal(restored.length,pair.elements.length+1);
const template={id:'move',kind:'widget',name:'이동',origin:'original',data:m.widget('go','button',0,0,20,10,{action:'gotoMap',target:'missing'})};
assert(m.validStudioPreset(b,template));
const refs=m.presetExternalTargets(b,template);assert.equal(refs[0].exists,false);refs[0].set.forEach(apply=>apply(b.startMap));
assert(m.presetExternalTargets(b,template)[0].exists);
b.characters[0].portrait=img;
let issues=await m.inspectOutput(b,'unity');assert(issues.some(i=>i.tool==='characters'&&i.owner===b.characters[0].id&&i.level==='error'));
b.characters[0].portrait='';b.scenes[0].hudId='orphan';issues=await m.inspectOutput(b,'offline');assert(issues.some(i=>i.tool==='scene'&&i.owner===b.startMap));
const index=await m.nativePackIndex([['Assets/Tests/X.cs',png]],17,true);
assert.equal(index.revision,17);assert.equal(index.files[0].sha256,img.slice(6));assert.equal(index.kind,'project');
await assert.rejects(m.nativePackIndex([['Assets/Tests/X.cs',png],['Assets/Tests/x.cs',png]],17,true));
await assert.rejects(m.nativePackIndex([['ProjectSettings/DreamwalkerStudioImport.json',png]],17,true));
console.log('PASS portable asset digests, missing-media repair, external target remap, actor inheritance and overrides, editor-only assets, export destinations, verified Unity index');
